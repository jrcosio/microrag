"""Writes the Python string semantics the app's extraction must reproduce (F06 research R8).

The extractor in offline/eval/extract.py uses str.isspace, str.splitlines, str.isdigit and the
regex \\d of Python. Kotlin has no exact equivalent, so the code point sets are generated here and
compiled into the app. Usage: gen_pytext_tables.py [--check].
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "app/src/main/java/com/lisdatasolutions/microrag/rag/ingest/PyTables.kt"
MAX_CODE_POINT = sys.maxunicode


def ranges(predicate):
    out, start = [], None
    for cp in range(MAX_CODE_POINT + 1):
        inside = predicate(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CODE_POINT))
    return out


def line_breaks():
    return [cp for cp in range(MAX_CODE_POINT + 1) if len(f"a{chr(cp)}b".splitlines()) == 2]


def kotlin_array(name, doc, values):
    body = ",\n".join("        " + ", ".join(f"0x{v:X}" for v in values[i:i + 8]) for i in range(0, len(values), 8))
    return f"    /** {doc} */\n    val {name}: IntArray = intArrayOf(\n{body},\n    )\n"


def render():
    flat = lambda rs: [v for r in rs for v in r]  # noqa: E731
    python = ".".join(map(str, sys.version_info[:3]))
    return (
        f"// Generated by offline/gen_pytext_tables.py with Python {python} (Unicode {unicodedata.unidata_version}).\n"
        "// Do not edit: regenerate it and commit both files together.\n"
        "package com.lisdatasolutions.microrag.rag.ingest\n\n"
        "/**\n"
        " * Python string semantics that the extraction must reproduce exactly (F06 research R8). Ranges are\n"
        " * inclusive pairs `start, end` of code points.\n"
        " */\n"
        "internal object PyTables {\n"
        f"    const val UNICODE_VERSION = \"{unicodedata.unidata_version}\"\n\n"
        + kotlin_array("SPACE_RANGES", "Code points for which `str.isspace()` is true.", flat(ranges(str.isspace))) + "\n"
        + kotlin_array("LINE_BREAKS", "Line boundaries of `str.splitlines()`; CR LF counts as one.", line_breaks()) + "\n"
        + kotlin_array("DIGIT_RANGES", "Code points for which `str.isdigit()` is true.", flat(ranges(str.isdigit))) + "\n"
        + kotlin_array("DECIMAL_RANGES", "Code points matched by `\\\\d` in Python regexes (`str.isdecimal()`, category Nd).",
                       flat(ranges(str.isdecimal)))
        + "}\n"
    )


def main():
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{TARGET} is out of date")
        print("PyTables.kt up to date")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
