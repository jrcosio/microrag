"""Writes golden/answer_golden.jsonl (F11 contracts/eval-answer.md §1, rules G1–G6).

For every live question of the test set: the inputs of the prompt (question, previous turn and the blocks
of the decided configuration) with the prompt the desktop builds for them, and the answer generated by
the adopted template with how judge.py reads it. AnswerGoldenTest replays both with the app's port.

The prompt is kept as its length in code points and its SHA-256; its whole text only in ten fixed rows,
so a difference can be read without storing every prompt.

    offline/.venv/bin/python -I offline/gen_answer_golden.py [--check]
"""

import dataclasses
import hashlib
import json
import sys
from pathlib import Path

OFFLINE = Path(__file__).resolve().parent
sys.path.insert(0, str(OFFLINE))  # -I leaves the script directory out of sys.path

from eval import judge  # noqa: E402
from eval.pipeline import _blocks_of, decided_config, fingerprints, live_questions, load_context  # noqa: E402
from eval.prompt import build_prompt  # noqa: E402
from eval.retrieval import PARAMETERS  # noqa: E402
from eval.runs import EvalConfig, run_dir  # noqa: E402
from eval.selector import ContextBlock  # noqa: E402

GOLDEN = OFFLINE / "golden" / "answer_golden.jsonl"
FULL_FIRST = 5          # rows with the whole prompt: the first ones,
FULL_FOLLOW_UPS = 3     # the first follow-ups,
FULL_NULL_PARTS = 2     # and the first with a block without heading or page


def cited_order(citations, block_count):
    """The app's rule (F11 research R3): valid numbers in the order of their first citation, no repeats."""
    seen = []
    for n in citations:
        if 1 <= n <= block_count and n not in seen:
            seen.append(n)
    return seen


def build(ctx, template):
    """One row per live question; the answers come from the run of [template] on the decided configuration."""
    config = dataclasses.replace(decided_config(), llm="E2B", prompt_template=template)
    answers_path = run_dir(EvalConfig.fingerprint(config, *fingerprints(ctx, config))) / "answers.jsonl"
    if not answers_path.exists():
        raise SystemExit(f"no answers for template {template}: run run_eval.py template-review or generate first")
    answers = {json.loads(line)["id"]: json.loads(line)["answer"] for line in answers_path.read_text(encoding="utf-8").splitlines()}
    blocks = _blocks_of(ctx, config)
    questions = sorted(live_questions(), key=lambda q: q.id)
    by_id = {q.id: q for q in questions}
    rows = []
    for q in questions:
        context = [ContextBlock(**b) for b in blocks[q.id]]
        # G1: the previous turn of pipeline.generate, the previous question and its generated answer.
        previous = (by_id[q.previous].question, answers[q.previous]) if q.previous in by_id else None
        prompt = build_prompt(q.question, context, previous, template)
        answer = answers[q.id]
        citations = judge.citations(answer)
        rows.append({
            "id": q.id, "template": template, "question": q.question, "previous": list(previous) if previous else None,
            "blocks": [{"document_name": b.document_name, "heading_path": b.heading_path, "page": b.page, "text": b.text} for b in context],
            "prompt_chars": len(prompt), "prompt_sha256": hashlib.sha256(prompt.encode("utf-8")).hexdigest(), "prompt": prompt,
            "answer": answer, "citations": citations, "cited_order": cited_order(citations, len(context)),
            "refusal": judge.is_refusal(answer), "norm": judge.norm(answer),
        })
    keep = full_prompt_ids(rows)
    for row in rows:
        if row["id"] not in keep:
            row["prompt"] = None
    return rows


def full_prompt_ids(rows):
    first = [r["id"] for r in rows[:FULL_FIRST]]
    follow_ups = [r["id"] for r in rows if r["previous"] is not None and r["id"] not in first][:FULL_FOLLOW_UPS]
    null_parts = [r["id"] for r in rows if r["id"] not in first + follow_ups
                  and any(b["heading_path"] is None or b["page"] is None for b in r["blocks"])][:FULL_NULL_PARTS]
    return set(first + follow_ups + null_parts)


def render(rows):
    return "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows)


def main(argv=None):
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    template = json.loads(PARAMETERS.read_text(encoding="utf-8"))["prompt_template"]
    ctx = load_context("ref")
    text = render(build(ctx, template))
    ctx.db.close()
    if check:
        if not GOLDEN.exists() or GOLDEN.read_text(encoding="utf-8") != text:
            raise SystemExit(f"out of date: {GOLDEN.name}")
        print("answer golden up to date")
        return
    GOLDEN.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {text.count(chr(10))} rows ({template}) -> {GOLDEN}")


if __name__ == "__main__":
    main()
